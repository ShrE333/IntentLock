export function safeDiagnostic(error,stage){
  const code=error instanceof Error?(error.code??error.message):'';
  const oauth=typeof code==='string'&&code.match(/^PAYPAL_OAUTH_(\d{3}):TOKEN_REQUEST_FAILED$/);
  return {stage,...(Number.isInteger(error?.providerStatus)&&error.providerStatus>=100&&error.providerStatus<=599?{providerStatus:error.providerStatus}:{}),code:codes.has(code)?code:oauth?'PAYPAL_OAUTH_REJECTED':'UNEXPECTED_FAILURE',
    ...(Number.isInteger(error?.status)&&error.status>=100&&error.status<=599?{status:error.status}:oauth?{status:Number(oauth[1])}:{})};
}
